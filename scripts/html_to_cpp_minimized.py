Import("env") # type: ignore

from pathlib import Path
import requests
from SCons.Script import COMMAND_LINE_TARGETS  # type: ignore

HTML_PATH = Path("web") / "index.html"
CSS_PATH = Path("web") / "style.css"
JS_PATH = Path("web") / "script.js"
CPP_PATH = Path("include/embeddedWeb") / "webpage.h"
GENERATOR_PATH = Path("scripts") / "html_to_cpp_minimized.py"

HTML_MINIFY_API_URL = "https://www.toptal.com/developers/html-minifier/api/raw"
JS_MINIFY_API_URL = "https://www.toptal.com/developers/javascript-minifier/api/raw"
CSS_MINIFY_API_URL = "https://www.toptal.com/developers/cssminifier/api/raw"
MINIFY_TIMEOUT_SECONDS = 10

UPLOAD_TARGETS = {"upload", "program"}


def minify(content: str, url: str) -> str:
    try:
        response = requests.post(
            url,
            data={"input": content},
            timeout=10,
        )
        response.raise_for_status()

        minified = response.text
        if not minified:
            raise ValueError("Minifier API returned empty response")

        return minified

    except Exception as error:
        print(f"Minify failed: {error!r}")
        raise


def remove_external_references(html: str) -> str:
    js_tag = '<script src="script.js" defer></script>'
    css_tag = '<link rel="stylesheet" href="style.css" />'
    
    if js_tag not in html: raise ValueError(f"Missing script tag in HTML: {js_tag}")
    if css_tag not in html: raise ValueError(f"Missing style tag in HTML: {css_tag}")

    html = html.replace(js_tag, "")
    html = html.replace(css_tag, "")
    return html


def inline_css(html: str, css: str) -> str:
    closing_body = "</head>"

    if closing_body not in html:
        raise ValueError(f"Missing closing head tag in HTML: {closing_body}")

    inline_style = f"<style>{css}</style>"
    return html.replace(closing_body, f"{inline_style}{closing_body}")


def inline_js(html: str, js: str) -> str:
    closing_body = "</body>"

    if closing_body not in html:
        raise ValueError(f"Missing closing body tag in HTML: {closing_body}")

    inline_script = f"<script>{js}</script>"
    return html.replace(closing_body, f"{inline_script}{closing_body}")


def pick_safe_html_delimiter(html: str, base: str = "HTML") -> str:
    tag = base
    i = 0
    while f'){tag}"' in html:
        i += 1
        tag = f"{base}_{i}"
    return tag


def generate_cpp_header(html: str, source: Path, generator: Path) -> str:
    tag = pick_safe_html_delimiter(html)

    return (
        "#pragma once\n\n"
        f"// Generated by: {generator.as_posix()}\n"
        f'constexpr const char EMBEDDED_WEBPAGE[] = R"{tag}(\n'
        f"{html}\n"
        f'){tag}";\n'
    )


def write_if_changed(path: Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)

    if path.exists():
        current = path.read_text(encoding="utf-8")
        if current == content:
            return False

    path.write_text(content, encoding="utf-8", newline="\n")
    return True


def should_run() -> bool:
    return any(target in UPLOAD_TARGETS for target in COMMAND_LINE_TARGETS)


def main() -> None:
    project_dir = Path(env["PROJECT_DIR"]) # type: ignore

    html_src = project_dir / HTML_PATH
    css_src = project_dir / CSS_PATH
    js_src = project_dir / JS_PATH
    cpp_dst = project_dir / CPP_PATH

    if not html_src.exists(): raise FileNotFoundError(f"Missing source HTML: {html_src}")
    if not css_src.exists(): raise FileNotFoundError(f"Missing source CSS: {css_src}")
    if not js_src.exists(): raise FileNotFoundError(f"Missing source JS: {js_src}")

    # read source files
    html = html_src.read_text(encoding="utf-8")
    css = css_src.read_text(encoding="utf-8")
    js = js_src.read_text(encoding="utf-8")

    # remove external references from html
    html = remove_external_references(html)

    # minify content
    html_minified = minify(html, HTML_MINIFY_API_URL)
    js_minified = minify(js, JS_MINIFY_API_URL)
    css_minified = minify(css, CSS_MINIFY_API_URL)

    # Inline CSS and JS into HTML
    final_html = inline_css(html_minified, css_minified)
    final_html = inline_js(final_html, js_minified)

    output = generate_cpp_header(
        final_html,
        html_src.relative_to(project_dir),
        GENERATOR_PATH,
    )

    if write_if_changed(cpp_dst, output):
        print(f"[sync_html] Updated {CPP_PATH} from {HTML_PATH}")
    else:
        print(f"[sync_html] {CPP_PATH} already up to date")


if should_run():
    main()
else:
    print("[sync_html] Skipped (not an upload/program target)")
